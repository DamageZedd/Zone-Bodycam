"""Zone Bodycam - build the overlay textures from a TTF font and a logo image.

    py -I make_overlay_assets.py <font.ttf> <logo.png or -> <mod gamedata dir> [cyrillic.ttf]

Writes:
  textures\\ui\\zbc_font.dds          glyph atlas on a 16-wide grid, white glyphs with a baked black
                                     outline (like the real overlay's text outline): ASCII 32..126,
                                     then the Russian letters of the game's Windows-1251 text
                                     (Yo, yo, A..ya) when a Cyrillic font is given
  textures\\ui\\zbc_logo.dds          the logo, 128x128 (only when a logo image is given)
  scripts\\zbc_font_metrics.script   atlas layout for zbc_bodycam.script / zbc_allies.script
  scripts\\zbc_osd_atlas_cyr.script  the Russian letters as 16x32 2-bit rows for the in-shader
                                     overlay (bus_zbc_osd_atlas rows 816.., shaders\\r3\\zbc_osd.h)
Uncompressed 32-bit DDS, which the engine loads directly.

The main font has no Cyrillic, so those letters come from the second font, scaled to the main
font's capital height and squeezed to its fixed advance so they sit on the same grid.
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

COLS = 16
FIRST, LAST = 32, 126
CYR = [0xA8, 0xB8] + list(range(0xC0, 0x100))   # Windows-1251: Yo, yo, A..ya
CYR_BASE = LAST - FIRST + 1                     # atlas cell of the first Russian letter (95)
EM = 64                      # font size in atlas pixels
OUTLINE = max(2, round(EM * 0.045))   # the real overlay: 1 px outline on 1.2vw text, about 1/23 em
OSD_ASCII_ROWS = 816         # shader atlas rows already used: 94 ASCII glyphs x 8 + the 64-row logo

def cyr_char(code):
    return bytes([code]).decode("cp1251")

def bold(font):
    try:
        if b"Bold" in font.get_variation_names():
            font.set_variation_by_name(b"Bold")
    except Exception:
        pass                                          # not a variable font
    return font

def draw_cyrillic(atlas, cyr_ttf, font, cell_w, cell_h, advance):
    """Russian letters from cyr_ttf, matched to the main font's capitals and advance."""
    k_ascent = font.getmetrics()[0]
    k_cap = k_ascent - font.getbbox("H")[1]
    probe = bold(ImageFont.truetype(cyr_ttf, EM))
    r_cap = probe.getmetrics()[0] - probe.getbbox("Н")[1]
    fb = bold(ImageFont.truetype(cyr_ttf, round(EM * k_cap / r_cap)))
    fb_ascent = fb.getmetrics()[0]
    squeeze = min(1.0, advance / fb.getlength("М"))
    for n, code in enumerate(CYR):
        i = CYR_BASE + n
        cx, cy = (i % COLS) * cell_w, (i // COLS) * cell_h
        tmp_w = int(cell_w / squeeze) + 2
        tmp = Image.new("RGBA", (tmp_w, cell_h), (0, 0, 0, 0))
        # same baseline as the main font; origin placed so the squeezed glyph starts at the cell origin
        ox = (OUTLINE + 2) / squeeze
        oy = OUTLINE + 2 + (k_ascent - fb_ascent)
        ImageDraw.Draw(tmp).text((ox, oy), cyr_char(code), font=fb, fill=(255, 255, 255, 255),
                                 stroke_width=OUTLINE, stroke_fill=(0, 0, 0, 255))
        tmp = tmp.resize((max(1, round(tmp_w * squeeze)), cell_h), Image.LANCZOS)
        atlas.alpha_composite(tmp.crop((0, 0, cell_w, cell_h)), (cx, cy))

def build_font(ttf, out_dds, out_lua, cyr_ttf=None):
    font = ImageFont.truetype(ttf, EM)
    ascent, descent = font.getmetrics()
    advance = font.getlength("M")                     # monospace: every glyph advances the same
    cell_w = int(advance + 2 * OUTLINE + 4)
    cell_h = int(ascent + descent + 2 * OUTLINE + 4)
    count = CYR_BASE + (len(CYR) if cyr_ttf else 0)
    W, H = COLS * cell_w, ((count + COLS - 1) // COLS) * cell_h
    atlas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    draw = ImageDraw.Draw(atlas)
    for code in range(FIRST, LAST + 1):
        i = code - FIRST
        cx, cy = (i % COLS) * cell_w, (i // COLS) * cell_h
        x, y = cx + OUTLINE + 2, cy + OUTLINE + 2
        draw.text((x, y), chr(code), font=font, fill=(255, 255, 255, 255),
                  stroke_width=OUTLINE, stroke_fill=(0, 0, 0, 255))
    if cyr_ttf:
        draw_cyrillic(atlas, cyr_ttf, font, cell_w, cell_h, advance)
    atlas.save(out_dds, format="DDS")
    with open(out_lua, "w", encoding="ascii", newline="\r\n") as f:
        f.write("-- Zone Bodycam - glyph atlas layout, generated by tools\\make_overlay_assets.py\n")
        f.write("-- from %s%s. Do not edit by hand.\n" % (os.path.basename(ttf),
                (" + " + os.path.basename(cyr_ttf) + " (Russian letters)") if cyr_ttf else ""))
        f.write("texture = \"ui\\\\zbc_font\"\n")
        f.write("tex_w, tex_h = %d, %d\n" % (W, H))
        f.write("cols, first, last = %d, %d, %d\n" % (COLS, FIRST, LAST))
        f.write("cell_w, cell_h = %d, %d\n" % (cell_w, cell_h))
        f.write("em = %d\n" % EM)
        f.write("advance = %.3f\n" % advance)
        f.write("pad = %d\n" % (OUTLINE + 2))
        f.write("\n-- atlas cell (0-based) of a Windows-1251 character code; nil for a space or no glyph\n")
        f.write("function index(code)\n")
        f.write("\tif code > %d and code <= %d then return code - %d end\n" % (FIRST, LAST, FIRST))
        if cyr_ttf:
            f.write("\tif code == 168 then return %d end\n" % CYR_BASE)
            f.write("\tif code == 184 then return %d end\n" % (CYR_BASE + 1))
            f.write("\tif code >= 192 and code <= 255 then return code - 192 + %d end\n" % (CYR_BASE + 2))
        f.write("\treturn nil\n")
        f.write("end\n")
    return atlas, (W, H, cell_w, cell_h, advance)

def bake_osd_cyr(atlas, cell_w, cell_h, out_lua):
    """The Russian letters as 16x32 2-bit glyphs for the in-shader overlay, in the same encoding as the
    ASCII rows of zbc_osd_atlas.script (0 clear, 1 outline, 2 grey, 3 white; 16 px per uint, 2 bits
    each, 4 pixel rows per uint4). Checked against those rows: this bake reproduces 97.8% of them."""
    lines = []
    for n, code in enumerate(CYR):
        i = CYR_BASE + n
        cx, cy = (i % COLS) * cell_w, (i // COLS) * cell_h
        g = atlas.crop((cx, cy, cx + cell_w, cy + cell_h)).resize((16, 32), Image.LANCZOS)
        words = []
        for y in range(32):
            w = 0
            for x in range(16):
                r, gg, b, a = g.getpixel((x, y))
                l = (r + gg + b) / 765
                c = 0 if a / 255 < 0.2 else (1 if l < 0.3 else (2 if l < 0.8 else 3))
                w |= c << (2 * x)
            words.append(w)
        lines.append("\t-- cp1251 %d" % code)
        for r in range(8):
            lines.append("\t{ %d, %d, %d, %d }," % tuple(words[r * 4:r * 4 + 4]))
    with open(out_lua, "w", encoding="ascii", newline="\r\n") as f:
        f.write("-- Zone Bodycam - Russian letters for the in-shader overlay (zbc_osd_atlas_cyr.script)\n")
        f.write("-- Generated by tools\\make_overlay_assets.py from textures\\ui\\zbc_font.dds. Do not edit by hand.\n")
        f.write("-- Uploaded after zbc_osd_atlas.ROWS at bus_zbc_osd_atlas row OFFSET: cp1251 168, 184, then 192..255,\n")
        f.write("-- 8 rows per letter.\n")
        f.write("\nOFFSET = %d\n\nROWS = {\n" % OSD_ASCII_ROWS)
        f.write("\n".join(lines))
        f.write("\n}\n")

def build_logo(png, out_dds):
    img = Image.open(png).convert("RGBA")
    bbox = img.getbbox()                              # trim empty margins so the logo fills its box
    if bbox:
        img = img.crop(bbox)
    side = max(img.size)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.paste(img, ((side - img.size[0]) // 2, (side - img.size[1]) // 2))
    square.resize((128, 128), Image.LANCZOS).save(out_dds, format="DDS")

if __name__ == "__main__":
    ttf, logo, gamedata = sys.argv[1], sys.argv[2], sys.argv[3]
    cyr_ttf = sys.argv[4] if len(sys.argv) > 4 else None
    os.makedirs(os.path.join(gamedata, "textures", "ui"), exist_ok=True)
    os.makedirs(os.path.join(gamedata, "scripts"), exist_ok=True)
    atlas, info = build_font(
        ttf, os.path.join(gamedata, "textures", "ui", "zbc_font.dds"),
        os.path.join(gamedata, "scripts", "zbc_font_metrics.script"), cyr_ttf)
    print("font atlas: %dx%d, cell %dx%d, advance %.2f" % info)
    if cyr_ttf:
        bake_osd_cyr(atlas, info[2], info[3], os.path.join(gamedata, "scripts", "zbc_osd_atlas_cyr.script"))
        print("russian letters: %d, shader rows %d.." % (len(CYR), OSD_ASCII_ROWS))
    if logo != "-":
        build_logo(logo, os.path.join(gamedata, "textures", "ui", "zbc_logo.dds"))
        print("logo: 128x128")
