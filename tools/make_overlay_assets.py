"""Zone Bodycam - build the overlay textures from a TTF font and a logo image.

    py -I make_overlay_assets.py <font.ttf> <logo.png or -> <mod gamedata dir>

Writes:
  textures\\ui\\zbc_font.dds         glyph atlas, ASCII 32..126 on a 16x6 grid, white glyphs with a
                                    baked black outline (like the real overlay's text outline)
  textures\\ui\\zbc_logo.dds         the logo, 128x128 (only when a logo image is given)
  scripts\\zbc_font_metrics.script  atlas layout for zbc_bodycam.script
Uncompressed 32-bit DDS, which the engine loads directly.
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

COLS, ROWS = 16, 6
FIRST, LAST = 32, 126
EM = 64                      # font size in atlas pixels
OUTLINE = max(2, round(EM * 0.045))   # the real overlay: 1 px outline on 1.2vw text, about 1/23 em

def build_font(ttf, out_dds, out_lua):
    font = ImageFont.truetype(ttf, EM)
    ascent, descent = font.getmetrics()
    advance = font.getlength("M")                     # monospace: every glyph advances the same
    cell_w = int(advance + 2 * OUTLINE + 4)
    cell_h = int(ascent + descent + 2 * OUTLINE + 4)
    W, H = COLS * cell_w, ROWS * cell_h
    atlas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    draw = ImageDraw.Draw(atlas)
    for code in range(FIRST, LAST + 1):
        i = code - FIRST
        cx, cy = (i % COLS) * cell_w, (i // COLS) * cell_h
        x, y = cx + OUTLINE + 2, cy + OUTLINE + 2
        draw.text((x, y), chr(code), font=font, fill=(255, 255, 255, 255),
                  stroke_width=OUTLINE, stroke_fill=(0, 0, 0, 255))
    atlas.save(out_dds, format="DDS")
    with open(out_lua, "w", encoding="ascii", newline="\r\n") as f:
        f.write("-- Zone Bodycam - glyph atlas layout, generated by tools\\make_overlay_assets.py\n")
        f.write("-- from %s. Do not edit by hand.\n" % os.path.basename(ttf))
        f.write("texture = \"ui\\\\zbc_font\"\n")
        f.write("tex_w, tex_h = %d, %d\n" % (W, H))
        f.write("cols, first, last = %d, %d, %d\n" % (COLS, FIRST, LAST))
        f.write("cell_w, cell_h = %d, %d\n" % (cell_w, cell_h))
        f.write("em = %d\n" % EM)
        f.write("advance = %.3f\n" % advance)
        f.write("pad = %d\n" % (OUTLINE + 2))
    return W, H, cell_w, cell_h, advance

def build_logo(png, out_dds):
    img = Image.open(png).convert("RGBA")
    bbox = img.getbbox()                              # trim empty margins so the logo fills its box
    if bbox:
        img = img.crop(bbox)
    side = max(img.size)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.paste(img, ((side - img.size[0]) // 2, (side - img.size[1]) // 2))
    square.resize((128, 128), Image.LANCZOS).save(out_dds, format="DDS")

if __name__ == "__main__":
    ttf, logo, gamedata = sys.argv[1], sys.argv[2], sys.argv[3]
    os.makedirs(os.path.join(gamedata, "textures", "ui"), exist_ok=True)
    os.makedirs(os.path.join(gamedata, "scripts"), exist_ok=True)
    print("font atlas: %dx%d, cell %dx%d, advance %.2f" % build_font(
        ttf, os.path.join(gamedata, "textures", "ui", "zbc_font.dds"),
        os.path.join(gamedata, "scripts", "zbc_font_metrics.script")))
    if logo != "-":
        build_logo(logo, os.path.join(gamedata, "textures", "ui", "zbc_logo.dds"))
        print("logo: 128x128")
